/**
 * 走行ログの取り込み（`POST /api/logs`）の設定値。**コードに直書きしない**（`CLAUDE.md`）。
 *
 * ここの上限は好みではなく、**D1 の制限から逆算した値**である。
 * 根拠を消さないよう、それぞれの上限に何が効いているかを添えてある。
 */

/**
 * 1回のリクエストで受け取る件数の上限。
 *
 * **超えたら 400 を返して何も入れない。**黙って切り詰めると、
 * **送った側は成功したと思い、入らなかったぶんは誰にも見えないまま消える**——
 * 走行ログでこれをやると、集計に出ていないことが「起きていない」に見える。
 *
 * **スマホ側は、これを超える走行を分割して送る。**取り込みは冪等なので、
 * 分割しても、失敗して送り直しても二重に積まれない。
 */
export type LogLimits = {
  /** 1リクエストの走行の数 */
  maxRides: number;
  /**
   * 1リクエストの測位点の数（既定 5000 ＝ 1Hz でおよそ 83 分）。
   *
   * **効いているのは D1 の「1文 100,000 バイト」**（`buildInsertStatements`）。
   * 1行はおよそ 70 バイトなので、5000 点でも数文にしかならない。
   */
  maxPoints: number;
  /** 1リクエストの検知の数 */
  maxDetections: number;
};

export const logLimitDefaults: LogLimits = {
  maxRides: 20,
  maxPoints: 5_000,
  maxDetections: 2_000,
};

/**
 * **測位の値に上限を置かない**（`request.ts` が確かめるのは、緯度経度の範囲と、
 * 速度・精度が負でないことだけ）。
 *
 * 走行中の中継（`v2v/config.ts` の `messageLimitDefaults`）は `spd` と `hacc` に上限を置いて
 * 足切りしているが、**同じことをここでやらない。**
 *
 * - あちらは**壊れた1通を他人の近傍に入れない**ための足切りで、捨てても次の測位が1秒後に来る。
 *   **こちらは捨てたら二度と戻らない生ログ**である（`docs/adr/0007-keep-raw-ride-logs.md`）
 * - **1点でも上限を超えると、走行が丸ごと上がらなくなる。**取り込みは「壊れていたら1行も入れない」
 *   ——**GPS の速度が1回跳ねただけ**（悪い測位は簡単に 30 m/s を超える）で 400 になり、
 *   **スマホの手元のログは変わらないので、何度送り直しても同じところで落ちる。**
 *   その走行は永久に上がらない
 * - **精度の悪い点を捨てるのは取り込みの仕事ではない。**しきい値を変えて計算し直せることが
 *   生ログを残す理由なので、**足切りは計算する側（#85）が、そのときの設定で行う**
 *
 * **入れられない値だけを弾く**——緯度経度が地球の外、速度や精度が負、という「読みようがないもの」。
 *
 */

/**
 * 1つの INSERT 文の上限（バイト）。**D1 は1文 100,000 バイトまで**しか受け付けない。
 *
 * **バインド変数（`?`）を使わずに値を埋め込んでいるのは、D1 の別の制限のため**である。
 *
 * - **1つのクエリに渡せるバインド変数は 100 個まで。**測位点は9列なので**1文 11 行**にしかならず、
 *   5000 点で 455 文になる
 * - **1回の Worker の呼び出しで投げられるクエリは 50 個まで**（無料プラン。有料でも 1000）。
 *   **455 文はバッチにまとめても超える**——バッチの中の1文は1クエリとして数えられる
 *
 * **値を埋め込めば、5000 点でも数文で済む。**同じ理由で標識の取り込みも SQL を組み立てている
 * （`scripts/stop-signs/sql.ts`）。**埋め込んでよいのは、Zod が形を確かめた値だけ**である
 * （`request.ts`。文字列は 16進8文字か決まった語のどちらかしか通らない）。
 */
export const MAX_STATEMENT_BYTES = 80_000;
