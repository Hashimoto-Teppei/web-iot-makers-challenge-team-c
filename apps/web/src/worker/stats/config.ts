/**
 * 集計（`GET /api/stats/cells`）の設定値。**コードに直書きしない**（`CLAUDE.md`）。
 *
 * **数字の意味と既定値の根拠は `docs/interfaces/web-service.md`「しきい値の既定値」が正本。**
 * ここに書くのは、**その値をどこで受け取り、なぜ上限が要るか**だけである。
 *
 * **不停止のしきい値（`recompute/config.ts`）とは性質が違う。**あちらは
 * 「サーバーに既定値を持たない」——その場で変えて叩き直すためだった。
 * **こちらは公開の画面が既定値のまま叩く**ので、既定値をサーバーが持つ。
 */

/**
 * **セルの分解能はここに無い。**丸め方は `src/shared/cell.ts` が持っている
 * ——**画面も同じ升目を使う**ので、片方にしか無いと半セルの足し方が2箇所に書かれる。
 */

export type StatsLimits = {
  /**
   * 順位に出す通過の下限（既定5走行）。
   *
   * **1回しか通っていない場所で1件出れば率は 100%** になり、ランキングの上位が
   * そればかりになる（`docs/interfaces/web-service.md`「率で見る」）。
   * **クエリで上書きできる**——実データを見て動かす数字なので、叩く側から変えられる。
   */
  minRides: number;
  /**
   * 1回で返すセルの数（既定 500）。
   *
   * **率の高い順に切る。**画面が扱える量に上限を置くためのもので、
   * **打ち切ったことは応答の `truncated` で伝える**——黙って切ると、
   * **出ていないことが「そこに何も無い」に見える。**
   */
  maxCells: number;
};

export const statsDefaults: StatsLimits = {
  minRides: 5,
  maxCells: 500,
};

/**
 * 検知を測位点に突き合わせるときに許す時刻のずれ（ミリ秒、既定 5,000）。
 *
 * **デバイス発の検知には位置が入っていない**ので、`t` で測位点に突き合わせて場所を決める
 * （`docs/interfaces/web-service.md`「検知を場所に結びつける」）。
 * **測位は 1Hz** なので、正常なら 1 秒以内に点がある。
 *
 * **上限を置かないと、測位が出ていない（`nofix`）間の検知が、
 * 何十秒も離れた別の場所の点に付く。**離れすぎたものは**「場所不明」として数だけ残す**
 * ——**黙って捨てると、集計に出ていないことが「起きていない」に見える。**
 */
export const MAX_MATCH_GAP_MS = 5_000;

/**
 * 1回の集計で読む測位点の上限（既定 50,000）。
 *
 * **通過（率の分母）は測位点を数えて出す**ので、集計は走行ログを全部読む。
 * **集計結果のテーブルは最初から作らないと決めている**（`docs/interfaces/web-service.md`
 * 「テーブル（D1）」。データ量が小さいうちは読むときに集計すれば足りる）ので、
 * **この上限に当たったときが、その表を足す時期が来たという合図**である。
 *
 * **Worker が持てる量から決めている。**メモリの上限は 128MB で、読んだ点は
 * **そのまま配列に載り、検知の突き合わせで端末ごとにもう一度並べ替えられる**
 * （`aggregate.ts`）。**大きすぎる上限は 503 の代わりに Worker ごと落ちる**
 * ——落ちると「集計表を足す時期だ」という合図が出ないまま、原因の分からない失敗になる。
 * 50,000 点は 1Hz でおよそ 28 走行時間ぶんで、**ハッカソンの規模では当たらない。**
 *
 * **超えたら打ち切らずに落とす。**途中まで読んだ点で集計すると、
 * **分母だけが小さい率**——つまり**実際より危険に見える順位**——が出る。
 */
export const MAX_RIDE_POINTS = 50_000;
