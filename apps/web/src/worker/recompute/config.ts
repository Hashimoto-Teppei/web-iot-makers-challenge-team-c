/**
 * 不停止の再計算（`POST /api/admin/recompute`）の設定値。**コードに直書きしない**（`CLAUDE.md`）。
 *
 * **しきい値はここに無い。**停止と見なす速度・標識から見る距離・進入方向のずれ・
 * 測位精度の足切りは、**リクエストで受け取る**（`request.ts`）。
 * **サーバーに既定値を持たせない**——その場で数字を変えて叩き直せることが、
 * この経路を持つ理由そのものである（`docs/interfaces/web-service.md`「いつ計算するか」）。
 * 暫定の既定値は `docs/interfaces/web-service.md`「しきい値の既定値」にあり、
 * **叩く側が毎回そこから写して渡す。**
 *
 * ここにあるのは**1回で扱う量の上限**だけで、これは好みではなく Worker と D1 の制限から来ている。
 */

export type RecomputeLimits = {
  /**
   * 1回で計算する走行の数（既定 20）。
   *
   * **効いているのは Worker の CPU 時間と D1 の読み取り行数**である。1走行は最大 5,000 点
   * （`logs/config.ts`）で、判定は「点 × 候補の標識」を回る（`judge.ts`）。
   * **超えたら 400 を返して1行も触らない**——途中まで計算して返すと、
   * **どこまで作り直せたのかが呼んだ側に分からない。**
   */
  maxRides: number;
  /**
   * 標識から見る距離の上限（メートル、既定 200）。
   *
   * **しきい値そのものではなく、しきい値に置ける上限**である。読み込む標識の数は
   * 走行の範囲をこの距離だけ広げた矩形で決まるので（`query.ts`）、
   * **大きな値を渡されると県ぶんの標識を丸ごと読むことになる。**
   */
  maxRadiusM: number;
};

export const recomputeLimitDefaults: RecomputeLimits = {
  maxRides: 20,
  maxRadiusM: 200,
};

/**
 * 1つの INSERT 文の上限（バイト）。**D1 は1文 100,000 バイトまで。**
 *
 * 理由は `logs/config.ts` の `MAX_STATEMENT_BYTES` と同じ（バインド変数 100 個 /
 * 1回の呼び出しで 50 クエリ）。**不停止の行は測位点よりずっと少ない**が、
 * **同じ理由で同じ組み立て方をする**——ここだけ Drizzle の `insert()` に戻すと、
 * 走行が増えたときに黙って上限に当たる。
 */
export const MAX_STATEMENT_BYTES = 80_000;

/**
 * 走行の方角を出すのに要る、2点間の最小の距離（メートル）。
 *
 * **しきい値ではなく、方角が意味を持つ最小の長さ**である（判定の当たりを調整する数字ではない
 * ので、リクエストでは受け取らない）。1Hz の測位は**止まっていても数十 cm のゆらぎを出す**ので、
 * **近すぎる2点から方角を出すと、そのゆらぎがそのまま方角になる。**
 * 5m は 1.5 m/s（停止と見なす速度の既定）で3秒ぶんの移動に当たる。
 *
 * **これより離れた点が見つからなければ、その訪問は判定しない**（`judge.ts`）
 * ——**見逃す側に倒す。**
 */
export const MIN_BEARING_SPAN_M = 5;
