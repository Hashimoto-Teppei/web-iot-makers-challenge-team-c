/**
 * 円の半径（メートル）＝ `RADIUS_PER_SQRT_RIDE × √通行`、ただし `MIN_RADIUS_M` を下回らない。
 *
 * **通行そのものに比例させてはいけない**（`docs/interfaces/web-ui.md`「地図の描き方」）。
 * **人は円の面積で量を読む**ので、半径を2倍にすると面積は4倍に見え、
 * **2倍の場所が4倍危険に見える。平方根を取ると、面積が通行に比例する。**
 *
 * **床を置くのは、通行の少ない区画が点になって見つけられないから**である。
 * **通行の下限は画面から 0 まで下げられる**ので（`StatsPage.tsx`）、
 * **床が無いと 1走行の区画が半径 11m の点になる。**
 * **床に当たった円どうしは大きさで比べられない**が、**そこは色（率）で読む場所**であり、
 * **見えない円よりは読める。**
 *
 * 係数を 14 から 11 へ下げたのは、**大きい側を伸ばしたときにセルの大きさ
 * （南北およそ 111m）を超えさせないため**（通行 48走行で半径 76m）。
 */
export const RADIUS_PER_SQRT_RIDE = 11;
export const MIN_RADIUS_M = 20;
export const radiusForRides = (rides: number): number =>
  Math.max(MIN_RADIUS_M, RADIUS_PER_SQRT_RIDE * Math.sqrt(rides));

/**
 * 画面に出す危険率（整数のパーセント）。**色の段も順位表の数字もこれで決める。**
 *
 * **率そのもので色を決めてはいけない。**`0.004` は **「0%」と表示されるのに 0 より大きい**ので、
 * **「0%」の行と円が「1〜9%」の色になる**——**危険が1件も出ていない場所が赤い**という、
 * 避けたかったものがそのまま出る（通行が 200 走行を超えれば起こる）。
 * **表示と色を1つの値から出すために、ここに置いてある。**
 */
export const ratePercent = (rate: number): number => Math.round(rate * 100);

/**
 * 危険率の段。**濃さではなく色で段を作る**（変更・2026-09-08。#157）。
 *
 * **以前は赤1色の不透明度（0.12〜0.75）で率を表していたが、段を数えられなかった。**
 * 地図の地を一段暗くしたことで**率 0 と率 1 の輝度比は 2.57:1 まで落ちており**
 * （下の `MAP_STYLES`）、**同じ色の半透明を重ねるやり方では、これ以上の差を作れない。**
 * **色相を動かすと、明るさが近くても人は段を見分けられる。**
 *
 * **段を離散にするのは、凡例を作れるようにするため**である（`./Legend.tsx`）。
 * **連続のグラデーションでは「この濃さは何%か」を読めない**ので、
 * 抑揚を付けても**「なんとなく赤い地図」のまま**になる。
 *
 * **切れ目は固定のパーセントにする。**表示中のセルで正規化（分位数）すると、
 * **タブや通行の下限を切り替えるたびに、同じ色が違う率を指す。**
 *
 * **`#d7263d` は中位の段として残してある。**この値は `index.css` の `--danger`
 * （順位表の率の文字と選択行）と同じもので、**片方だけ変えないこと**
 * （`docs/interfaces/web-ui.md`「赤の実値は2箇所にある」）。
 *
 * **縁は段ごとに、塗りを暗くした色を持つ。**「そこに区画がある」ことを示すのは縁の役目で
 * （同上）、**低い段の塗り（黄）は明るい地の上でほとんど浮かない**——
 * **明るい地に向かう配色である以上、下の段が地に近づくのは避けられない**ので、
 * **見つけられるかどうかは縁が引き受ける。**
 */
export type RateBand = {
  /** この段に入る上限（**この値未満**のパーセント）。最後の段は `Number.POSITIVE_INFINITY`。 */
  readonly under: number;
  /** 凡例に出す文字。 */
  readonly label: string;
  readonly fill: string;
  readonly stroke: string;
};

/** 最後の段。**上限を持たない**ので、下の `bandForPercent` の受け皿にもなる。 */
const HIGHEST_BAND: RateBand = {
  under: Number.POSITIVE_INFINITY,
  label: "40% 以上",
  fill: "#8f1224",
  stroke: "#5a0714",
};

export const RATE_BANDS: readonly RateBand[] = [
  { under: 1, label: "0%", fill: "#f7c948", stroke: "#a97a08" },
  { under: 10, label: "1〜9%", fill: "#ef8f3c", stroke: "#b25e12" },
  { under: 20, label: "10〜19%", fill: "#e3572b", stroke: "#9e2f0d" },
  { under: 40, label: "20〜39%", fill: "#d7263d", stroke: "#921020" },
  HIGHEST_BAND,
];

/** 段を引く。**渡すのは `ratePercent()` を通した整数**（上の注記）。 */
export const bandForPercent = (percent: number): RateBand =>
  // 上限が無限大の段が最後にあるので `find` は必ず当たる。**当たらない形に変えないこと。**
  RATE_BANDS.find((band) => percent < band.under) ?? HIGHEST_BAND;

