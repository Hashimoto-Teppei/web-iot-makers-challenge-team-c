"""しきい値・ピン番号・ファイルの置き場所などの設定。

**コードに直書きしない値をここへ集める**（`../../README.md`）。実地で変わる値を探すとき、
読む場所を1つにするため。

**秘密値は置かない。** このファイルはコミットされ、リポジトリは public
（`../../../../CLAUDE.md`「機密情報の扱い」）。
"""

from pathlib import Path

from device.notify import LightPattern, NotifyConfig, Tone

# device_id を保存する場所。
#
# **ログとは別のファイルに置く。** 一緒に消えると device_id が変わり、取り込みの一意キー
# `(device_id, log_id, seq)` が総入れ替えになって履歴がまるごと重複する
# （`../../../../docs/interfaces/ble-gatt.md`）。
#
# パスの区切りをハードコードしないよう pathlib で組み立てる（Windows の開発機でも
# import できる必要がある。ここは BLE を知らないので pytest から読まれる）。
IDENTITY_PATH = Path.home() / ".local" / "share" / "bike-device" / "identity.json"

# 使う Bluetooth アダプタのアドレス。None なら最初に見つかったものを使う。
# ラズパイに載っているのは1つだけなので、通常は None のままでよい。
BLE_ADAPTER_ADDRESS: str | None = None

# status の Notify を送る間隔（秒）。
#
# 値が変わったときだけ送る作りにすると、**心拍が途切れて link が down に落ちたことを
# セントラルへ伝える経路が、そのまま止まる**（変化を検出する側も止まっているため）。
# 一定間隔で送り続ける方が、届いていないことに気づける。
STATUS_NOTIFY_INTERVAL_S = 1

# 同じ理由で `alert` を捨て続けたとき、何通に1行 journalctl へ出すか。
#
# **毎通出さない。** `beat` は毎秒来るので、アプリが `st` の綴りを1つ間違えているだけで
# 毎秒1行になり、**`beat` をログに出さないことにした理由（SD カードへの書き込みと見通し）を
# こちらから壊す**（`hw/ble.py`）。1行目は必ず出るので、起きていること自体は分かる。
ALERT_DROP_LOG_EVERY = 100

# 最後の `beat` からこれだけ空いたら `link` を `down` にする（秒）。
#
# **`beat` は毎秒1通**なので、3 秒は「3通続けて落ちたら」に当たる。1〜2 秒にすると、
# BLE の接続間隔のゆらぎや GC で1通遅れただけで `down` に落ち、**表示が点滅する。**
# 逆に長くすると、スマホが落ちたことに気づくのが遅れる。
# **仮の値**（`../../../../docs/unverified.md` 50）。実機で `beat` の間隔を測ってから詰める。
LINK_BEAT_TIMEOUT_S = 3

# `beat` の `t` が進んでいるかを見る窓の長さ（秒）。
#
# **この窓いっぱい同じ `t` が続いたときだけ**「固まっている」と見なす
# （`../../../../docs/interfaces/v2v.md`「`t` が進んでいるかも見る」）。
# 上のタイムアウトより長くする —— **短いと、届いてはいるが `t` が1通ぶん止まっただけで
# `down` に落ちる。** 仮の値（`../../../../docs/unverified.md` 50）。
LINK_STALL_WINDOW_S = 5

# ウォッチドッグを回す間隔（秒）。
#
# **`beat` が来たときだけ見る作りにしない。** 来なくなったことに気づけなくなる
# （それがこの仕組みの目的そのもの）。タイムアウトより十分短くすること。
LINK_TICK_INTERVAL_S = 1

# `link` が `down` のままこれだけ続いたら、デバイスの側から接続を切る（秒）。
#
# **他人がつなぎっぱなしにすると、持ち主のスマホは接続できない**（接続枠は1つで、
# 枠を奪う手段はセントラル側に無い）。デバイスが手放せば、**アプリの再接続だけで戻せる**
# ——電源を切らなくてよくなる（`../../../../docs/interfaces/ble-gatt.md`「前提」）。
#
# **`LINK_BEAT_TIMEOUT_S` より十分長くする。** 揃えると、心拍が1通遅れただけで接続ごと落ち、
# 持ち主のアプリが**つながっては切られるを繰り返す。** 逆に長すぎると、
# 他人につかまれている時間がそのまま「警告が出ない時間」になる。
# **仮の値**（`../../../../docs/unverified.md` 91）。
IDLE_DISCONNECT_S = 30

# 周期処理（ウォッチドッグ）で例外が出続けたとき、何回に1本 journalctl へ出すか。
#
# **毎回出さない。** 周期は毎秒なので、つないだ先が恒常的に落ちていると
# 1日で8万本以上のトレースバックが SD カードに書かれ、**`link` が変わったという
# 一番読みたい行がその中に埋もれる**（`ALERT_DROP_LOG_EVERY` と同じ理由）。
# 1本目は必ず出るので、起きていること自体は分かる。
TICK_ERROR_LOG_EVERY = 60

# --- 警告の出し分け（`../../../../docs/notifications/arbitration.md`） ---
#
# **時間・回数・記号はすべて仮の値**（`../../../../docs/unverified.md` 45 / 46）。
# 実地で調整するため、`notify.py` に直書きせずここへ集める。

NOTIFY_CONFIG = NotifyConfig(
    # `lv` ごとの保持時間（ms）。**危険が去ったという通知は届かない**ので、時間で消すしかない。
    #
    # **`lv 1` を 3 秒にしてあるのは、スマホ側の再送間隔（2 秒）より長くするため。**
    # 揃えると、保持が切れてから次の再送が届くまでの隙間で表示が消える——BLE の書き込みは
    # 必ず多少遅れるので、これは確率ではなく毎回起きる。**片方だけ調整しないこと。**
    hold_ms={1: 3_000, 2: 4_000, 3: 6_000},
    # `lv` ごとに鳴らすもの。**`kind` では分けない**——5種類の音を走行中に聞き分けることは
    # できず、増やすと3段階の区別まで一緒に潰れる。
    tones={
        1: Tone(beeps=1, on_ms=100, gap_ms=0),
        2: Tone(beeps=2, on_ms=100, gap_ms=100),
        3: Tone(beeps=2, on_ms=600, gap_ms=200),
    },
    # `lv` ごとの光。**`lv 3` は点灯**（点滅させない）。
    lights={
        1: LightPattern(lit=True, blink_hz=0.5),
        2: LightPattern(lit=True, blink_hz=2.0),
        3: LightPattern(lit=True, blink_hz=None),
    },
    # `kind` の記号。**4文字固定・英大文字。半角カタカナを混ぜない**——1つだけカナにすると
    # そこだけ「読む」動作が要る。5つとも同じ文字種・同じ4桁なら桁の形だけで見分けられる。
    symbols={
        "rear_object": "REAR",
        "approach": "APPR",
        "brake": "BRK ",
        "corner": "CRNR",
        "stop": "STOP",
    },
    # 同じ `lv` が並んだときの順（強い順）。**後ろは振り向かないと見えず、通信が死んでいても
    # 出る唯一のもの**なので `rear_object` が先頭。以下、猶予の短い順。
    priority=("rear_object", "approach", "brake", "corner", "stop"),
    # 通信断のチャイム。**`lv 1` と同じ音を1回**。落ちた瞬間だけで、以後は鳴らさない。
    link_down_tone=Tone(beeps=1, on_ms=100, gap_ms=0),
)

# --- 部品の接続（`../../../../docs/hardware.md` が正本） ---
#
# **どれも `None` にできる。** `None` は「その部品が載っていない」という意味で、
# **実機を持たない開発者は4つとも `None` にすればハードウェアに触らずに起動できる**
# （`../../../../docs/adr/0002-development-lifecycle.md`）。
#
# **`enabled` のフラグを別に持たない。** 有効かどうかと番号の2箇所を見比べることになり、
# 片方だけ書き換えたときに黙って食い違う。**1つの値で切る。**
#
# **GPIO 番号をコードに直書きしない**ため、ここに集める（`CLAUDE.md`）。
# **ただし配線の正本は `docs/hardware.md` であって、この値ではない。**
# ピンを変えるときは、先にあちらの表を更新すること（予約が早い者勝ちとして機能しなくなる）。

# LCD1602A（I2C 変換基板つき）のアドレス。
#
# **変換基板のチップで変わる。** PCF8574T なら 0x27、PCF8574AT なら 0x3F で、
# **見た目では分からない**。実機で `i2cdetect -y 1` を1回見て確定させる
# （`../../../../docs/hardware.md`）。
LCD_I2C_ADDRESS: int | None = 0x27

# `light` チャンネルの LED。**抵抗を経由して GPIO へ直結してよい**のは LED 1個まで
# （`../../../../docs/adr/0003-hardware-wiring.md`）。
LIGHT_GPIO: int | None = 22

# `tone` チャンネルのブザー。**GPIO から直接駆動しない**——トランジスタを挟む（同上）。
#
# **自励式（音程を作れない）ブザーを使う。** `NOTIFY_CONFIG` の `tones` は
# 鳴らす回数と長さしか指定していないので、音程が無くても仕様どおりに鳴らせる。
BUZZER_GPIO: int | None = 17

# AE-NJR4265 J1 の検知(接近)出力（端子5）。**離反の出力は読まない**——遠ざかる物体は危険ではない。
#
# **VDD は 3.3V。** 出力は CMOS で H のとき VDD がそのまま出るため、
# **5V で駆動すると 5V が GPIO に乗って壊れる**（`../../../../docs/unverified.md` 28）。
#
# **検知距離はここに無い。** 基板の半固定抵抗 VR1 で決まり、**ツマミの位置が正本**である
# （`../../../../docs/hardware.md`）。
REAR_SENSOR_GPIO: int | None = 27
