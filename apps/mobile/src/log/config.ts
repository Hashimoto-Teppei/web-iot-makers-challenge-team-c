/**
 * 走行ログを端末に置いておく期間の設定。**コードに直書きしない**（`CLAUDE.md`）。
 *
 * **送る件数の上限（`./sync.ts` の `syncLimitDefaults`）はここに置かない。**
 * あちらは**取り込み側が正本**（`web/src/worker/logs/config.ts`）で、
 * ここにあるのは**端末だけで完結する判断**である。
 */

/**
 * 送り終えた行を、いつまで端末に置いておくか。
 *
 * **消す対象は `sent_at` が立っている行だけ**である（`./store.ts` の `purgeSent`）。
 * **送っていない行は、何日経っても消さない**——消すと**二度と上がらない。**
 */
export type RideLogRetention = {
  /**
   * 送信済みの行を残す時間（ミリ秒）。
   *
   * **0 にすれば送った直後に消える。**そうしていないのは、
   * **サーバー側にある確証が「200 が返ったこと」だけ**だからである
   * （取り込みは**受け取った件数**を返し、入った件数は返さない。
   * `web/src/worker/logs/request.ts`）。**取り込みで何かを取りこぼしていたとき、
   * 気づくのは早くても翌日**——その日のうちに手元から消えていると、
   * **何が入らなかったのかを確かめる術がなくなる。**
   *
   * **長くしすぎない理由の方が重い。**走行ログは**個人情報**であり（`CLAUDE.md`）、
   * **もうサーバーにあるものを端末に置き続ける理由が無い。**
   * **スマホを無くしたときに出ていくものを、必要のない範囲まで広げない。**
   *
   * **3日は「デモの前日に走って、当日に見返せる」ぶん**として置いた暫定値である
   * （`docs/unverified.md`）。1Hz で 3,600 行/時間なので、
   * **毎日1時間走っても手元に残るのはおよそ 1 万行**にとどまる。
   */
  sentRetentionMs: number;
};

export const rideLogRetentionDefaults: RideLogRetention = {
  sentRetentionMs: 3 * 24 * 60 * 60 * 1_000,
};
