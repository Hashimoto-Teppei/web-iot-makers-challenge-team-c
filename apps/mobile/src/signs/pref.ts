/**
 * 県コードを人に見せる形にする。
 *
 * **知らないコードを名前で騙らない。**画面が見せているのは「いま何を持っているか」
 * なので、**名前を知らないなら番号のまま出す**——別の県の同梱物を持っている端末に
 * 「岡山県」と表示するのが一番まずい。
 */
export function prefLabel(pref: number | null): string {
  if (pref === null) return "不明";
  return PREF_NAMES[pref] ?? `都道府県コード ${pref}`;
}
