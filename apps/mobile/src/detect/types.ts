/**
 * 4つの検知が共有する型。
 *
 * **型の正本はこのファイル。**`docs/interfaces/detectors.md` にも同じ形が載っているが、
 * あちらは決めたときの記録であり、食い違ったらこちらを正とする（あの文書自身がそう定めている）。
 * **フィールドを増やすときは、あちらの説明も併せて直すこと。**
 *
 * 決めた理由・使い分けの背景は `docs/interfaces/detectors.md` にある。ここには
 * 実装が守るべきことだけを書く。
 *
 * ここに置くのは「検知の入口と出口の形」だけで、しきい値の型と既定値は各検知の
 * ファイル（`approach.ts` など）に置く。まとめると4人が同じファイルを編集して
 * 必ずコンフリクトするため。
 */

/**
 * 1回の測位。
 *
 * `docs/interfaces/v2v.md`「メッセージ」の `self` / `peer` から `k` と `id` を落とし、
 * `rxAt` を足しただけのもの。単位も m/s と度のままで、ここで換算しない。
 */
export type Fix = {
  /**
   * 測位した時刻（UTC ミリ秒）。打ったのは**測位した端末の時計**。
   *
   * 同じ `Track` の中の2点の間隔にだけ使う（減速度など）。同じ端末の中の2点なら
   * 時計のずれは引き算で消える。`now - peer.t` のように自分の時計と混ぜないこと。
   */
  t: number;
  /**
   * この測位を手にした時刻（UTC ミリ秒）。打つのは**自分の時計**。
   *
   * 「その位置が何秒前のものか」は `now - rxAt` で出す。誰の `Track` でも引き算できる。
   * `peer` ではレスポンスを受け取った時刻、`self` では測位を受け取った時刻。
   * `self` は `t` とほぼ同じ値になるが、検知が `self` と `peer` で違う書き方を
   * しなくて済むように同じ形に揃えてある。
   */
  rxAt: number;
  /** 緯度（度、WGS84） */
  lat: number;
  /** 経度（度、WGS84） */
  lon: number;
  /** 対地速度（m/s） */
  spd: number;
  /** 進行方角（度、真北 0、時計回り 0〜360未満）。低速時は null */
  crs: number | null;
  /** 水平位置精度（メートル） */
  hacc: number;
};

/** 1台の端末の測位の履歴。 */
export type Track = {
  /** 端末ID（16進の小文字8文字）。自車は自分の id */
  id: string;
  /**
   * 古い順。末尾が最新。
   *
   * **空にしない。**この型が `readonly Fix[]` ではなく「先頭が必ず1つある配列」なのは、
   * 空を渡せないことを型で止めるため。空の `Track` を作るくらいなら、その `Track` を
   * `peers` に入れないこと（古い測位を捨てた結果 0 件になった相手も同じ）。
   *
   * おかげで検知の側は `fixes[fixes.length - 1]` を undefined の確認なしに書ける。
   * 呼び出し側は配列から作るときに非空を確かめる必要があるが、**確かめる場所が
   * 1か所に集まる方が、4つの検知それぞれで空を気にするより安全。**
   */
  fixes: readonly [Fix, ...Fix[]];
};

/** 一時停止の標識。 */
export type StopSign = {
  id: string;
  /** 規制地点の緯度（度、WGS84）。**停止線の位置とは限らず、交差点中央部のこともある** */
  lat: number;
  /** 規制地点の経度（度、WGS84） */
  lon: number;
  /**
   * **この標識が対象とする車両の進入方向**を表す点（度、WGS84）。
   * **この点から `(lat, lon)` へ向かって走る車両**が規制の対象になる。
   *
   * **単に近いだけで拾うと、対向車線や交差する道路の標識で警告が鳴る。**
   * 元データ（JARTIC の「進入方向（座標）」）が方向ごとに持っているので、
   * **1つの交差点に複数の進入方向があれば、標識も方向のぶんだけ別々の行になる**
   * （`docs/interfaces/mobile-api.md`）。
   *
   * **`null` は「全方向が対象」ではなく「元データに登録が無い」**。
   * 方向で絞れないので、**扱いは検知側が決める**（#27）。
   */
  approach: { lat: number; lon: number } | null;
};

/**
 * 4つの検知がすべて受け取る入力。
 *
 * 使わないフィールドがあってよい（急接近は `signs` を見ない）。それでも入力型を
 * 分けないのは、呼び出し側が4つを同じ形で回せることの方が価値があるため。
 */
export type DetectorInput = {
  /**
   * 自分の時計の「いま」（UTC ミリ秒）。
   *
   * `self.fixes` の最新の `t` ではない。測位が止まっている間も `now` は進むので、
   * 「最後の測位から何秒経ったか」が検知の中で分かる。
   */
  now: number;
  /** 自車。測位が無い間はそもそも検知を呼ばない（空の `self` を渡さない） */
  self: Track;
  /** 近傍の他車。空でありうる。空を「相手が居ない」と読み替えないこと */
  peers: readonly Track[];
  /** 近傍の一時停止の標識。空でありうる。絞るのは呼び出し側の責務 */
  signs: readonly StopSign[];
};

/**
 * 何の検知か。
 *
 * 値の正本は `docs/interfaces/ble-log-transfer.md`「検知ログの `body`」。
 * D1 の `detections` に入るのも同じ値なので、短く書き換えない
 * （同じ検知が2つの名前で入り、種別ごとの集計が割れる）。
 */
export type WarnKind =
  /** 急接近する自転車（#9） */
  | "approach"
  /** 前方車両の急ブレーキ（#10） */
  | "brake"
  /** 見えない曲がり角の対向車（#11） */
  | "corner"
  /** 一時停止の標識が近い（#27） */
  | "stop"
  /**
   * 後方から接近する物体（#26）。
   *
   * **これはデバイスの中で発生する。**スマホ側の検知がこの値を返すことは無い。
   * それでも一覧に載せているのは、デバイス上で他の警告と出力を取り合う相手だから。
   */
  | "rear_object";

/**
 * 警告の強さ。
 *
 * 「確からしさ」に使わない。測位が粗くて自信が無いことを 1 で表すと、余裕のある危険と
 * 危ないかもしれない危険が同じ表示になる。出すと決めたなら危険さで段階を付ける。
 *
 * - 1: 気づいてほしい。まだ余裕がある
 * - 2: 対処が要る。速度を落とす・進路を変える
 * - 3: 直ちに危険。間に合わないかもしれない
 */
export type WarnLevel = 1 | 2 | 3;

/** 検知の結果。警告が無ければ返すのは `null` であって、この形ではない。 */
export type Warning = {
  kind: WarnKind;
  lv: WarnLevel;
  /**
   * 発火の原因になったもの（相手の `Track.id` / `StopSign.id`）。
   *
   * BLE を通らないし D1 にも入らない。スマホの中で、同じ相手の警告を抑制するためだけに持つ。
   * 車車間の3つとは ID の形式が違う（標識の id が入る）ので、**抑制する側は `kind` と
   * 組にして扱うこと。**`kind` を無視して ID だけで突き合わせると、たまたま一致した
   * 標識と自転車が同じものとして抑制される。
   */
  causeId?: string;
};

/**
 * 検知そのもの。**関数1つである。**クラスにもオブジェクトにもしない。
 *
 * - ハードウェアにも通信にも触れない（測位の読み取り・BLE・HTTP・React Native の API）
 * - `Date.now()` を呼ばない。「いま」は `input.now` で受け取る
 * - 乱数を使わない。前回の呼び出しを覚えない（履歴は呼び出し側が `Track.fixes` で渡す）
 *
 * 返す `null` は「危険が無い」ではなく「**この検知は何も言えない**」である。
 * 検知は「安全である」という出力を持たない。分からないことを人に伝えるのは
 * 心拍と `link` の仕組みの側（`docs/interfaces/v2v.md`）。
 *
 * 1回の呼び出しで返すのは最大1つ。複数の相手が該当したら `lv` が高いもの、
 * 同じなら近いものを1つ選ぶ（デバイスの出力は1組しかない）。
 *
 * @typeParam C - その検知のしきい値の型。検知ごとに違う（共通のしきい値を作らない）
 */
export type Detector<C> = (input: DetectorInput, config: C) => Warning | null;
